interface PatchResult {
  values: Record<string, string>;
  raw: string;
  redacted_keys?: string[];
  changed: string[];
  restart_required: boolean;
}

/** Shown for keys in `redacted_keys`: the API masks them for everyone, so there is nothing to reveal. */
const HIDDEN_VALUE = "•••••••• (hidden)";
const HIDDEN_HINT =
  "The panel never sends this secret to the browser. To change it, replace the masked value in the Raw file tab; saving the mask unchanged keeps the current value.";

function HiddenValue({ id }: { id?: string }) {
  return (
    <span id={id} className="inline-flex items-center gap-1 font-mono text-xs text-muted-foreground" title={HIDDEN_HINT}>
      <Lock className="size-3" aria-hidden /> {HIDDEN_VALUE}
    </span>
  );
}
const MANAGED_HELP: Record<string, string> = {
  "server-port": "Always 25565 inside the container. Change the public port on the Network tab.",
  "enable-rcon": "RCON is enabled so the panel console can send commands.",
  "rcon.port": "Internal RCON port; it is never published outside the container.",
  "rcon.password": "Generated by MCPanel and rotated automatically.",
};
const INVALID_KEY = /[=:#!\s]/;
const LIVE = ["running", "starting", "unhealthy", "restarting"];

function validateValue(s: PropertySchema, v: string): string | null {
  if (s.type === "int") {
    if (v.trim() === "" || !/^-?\d+$/.test(v.trim())) return "Enter a whole number";
    const n = Number(v);
    if (s.min !== undefined && n < s.min) return `Must be at least ${s.min}`;
    if (s.max !== undefined && n > s.max) return `Must be at most ${s.max}`;
  }
  if (v.length > 4096) return "Too long (max 4096 characters)";
  return null;
}

function PropertyControl({
  schema,
  value,
  set,
  disabled,
  error,
}: {
  schema: PropertySchema;
  value: string | undefined;
  set: (v: string) => void;
  disabled: boolean;
  error: string | null;
}) {
  const id = `prop-${schema.key}`;
  const describedBy = [schema.help ? `${id}-help` : "", error ? `${id}-error` : ""].filter(Boolean).join(" ") || undefined;
  const unset = value === undefined;
  const keyHint = (
    <span className="truncate font-mono text-[10px] text-muted-foreground" title={schema.key}>
      {schema.key}
    </span>
  );
  if (schema.type === "bool") {
    return (
      <div className="grid grid-cols-1 gap-1">
        <div className="flex items-start justify-between gap-4">
          <div className="grid min-w-0 gap-0.5">
            <Label htmlFor={id}>{schema.label}</Label>
            {keyHint}
          </div>
          <Switch
            id={id}
            checked={value === "true"}
            onCheckedChange={(c) => set(c ? "true" : "false")}
            disabled={disabled}
            aria-describedby={describedBy}
          />
        </div>
        {schema.help && (
          <p id={`${id}-help`} className="text-xs text-muted-foreground">
            {schema.help}
          </p>
        )}
        {unset && <p className="text-[11px] text-muted-foreground italic">Not in the file — the server default applies.</p>}
      </div>
    );
  }
  return (
    <div className="grid grid-cols-1 content-start gap-1.5">
      <div className="grid min-w-0 gap-0.5">
        <Label htmlFor={id}>{schema.label}</Label>
        {keyHint}
      </div>
      {schema.type === "enum" ? (
        <Select value={value ?? ""} onValueChange={set} disabled={disabled}>
          <SelectTrigger id={id} className="w-full" aria-describedby={describedBy}>
            <SelectValue placeholder="Not set (server default)" />
          </SelectTrigger>
          <SelectContent>
            {(schema.options ?? []).map((o) => (
              <SelectItem key={o} value={o}>
                {o}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
      ) : (
        <Input
          id={id}
          type={schema.type === "int" ? "number" : "text"}
          inputMode={schema.type === "int" ? "numeric" : undefined}
          min={schema.min}
          max={schema.max}
          step={schema.type === "int" ? 1 : undefined}
          value={value ?? ""}
          placeholder={unset ? "Not set (server default)" : undefined}
          onChange={(e) => set(e.target.value)}
          disabled={disabled}
          aria-invalid={!!error || undefined}
          aria-describedby={describedBy}
          className={cn(schema.key === "motd" && "font-mono")}
          spellCheck={false}
        />
      )}
      {schema.help && (
        <p id={`${id}-help`} className="text-xs text-muted-foreground">
          {schema.help}
        </p>
      )}
      {schema.type === "int" && (schema.min !== undefined || schema.max !== undefined) && !error && (
        <p className="text-[11px] text-muted-foreground">
          {schema.min !== undefined && schema.max !== undefined
            ? `${schema.min} – ${schema.max}`
            : schema.min !== undefined
              ? `Minimum ${schema.min}`
              : `Maximum ${schema.max}`}
        </p>
      )}
      <FieldError id={`${id}-error`} message={error} />
    </div>
  );
}

function RestartBanner({
  instanceId,
  keys,
  canControl,
  running,
  onDismiss,
}: {
  instanceId: string;
  keys: string[];
  canControl: boolean;
  running: boolean;
  onDismiss: () => void;
}) {
  const invalidate = useInvalidateInstance();
  const restart = useMutation({
    mutationFn: () => api.post(`/instances/${instanceId}/power`, { action: "restart" }),
    onSuccess: () => {
      toast.success("Restart requested");
      invalidate(instanceId);
      onDismiss();
    },
    onError: (err) => toast.error(errorMessage(err)),
  });
  return (
    <Notice
      tone="warning"
      title="Restart the server to apply these changes"
      action={
        <>
          {canControl && running && (
            <Button size="sm" variant="outline" onClick={() => restart.mutate()} disabled={restart.isPending}>
              {restart.isPending ? <Loader2 className="animate-spin" /> : <RotateCw />} Restart now
            </Button>
          )}
          <Button size="icon-sm" variant="ghost" aria-label="Dismiss" onClick={onDismiss}>
            <X />
          </Button>
        </>
      }
    >
      The running server only reads server.properties at startup. Changed: <span className="font-mono">{keys.join(", ")}</span>
    </Notice>
  );
}

export function PropertiesTab({ instance, can, onDirtyChange }: TabProps) {
  const qc = useQueryClient();
  const canEdit = can("instance.configure");
  const key = qk.properties(instance.id);
  const q = useQuery({
    queryKey: key,
    queryFn: () => api.get<PropertiesResponse>(`/instances/${instance.id}/properties`),
    staleTime: 10_000,
  });
  const [mode, setMode] = useState<"form" | "raw">("form");
  const [drafts, setDrafts] = useState<Record<string, string | null>>({});
  const [rawDraft, setRawDraft] = useState<{ base: string; text: string } | null>(null);
  const [restartKeys, setRestartKeys] = useState<string[] | null>(null);
  const [filter, setFilter] = useState("");
  const [newKey, setNewKey] = useState("");
  const [newValue, setNewValue] = useState("");

  const data = q.data;
  const values = useMemo(() => data?.values ?? {}, [data]);
  const schemaKeys = useMemo(() => new Set((data?.schema ?? []).map((s) => s.key)), [data]);
  const managed = useMemo(() => new Set(data?.managed_keys ?? []), [data]);
  const redacted = useMemo(() => new Set(data?.redacted_keys ?? []), [data]);

  const changes = useMemo(() => {
    const out: Record<string, string | null> = {};
    for (const [k, v] of Object.entries(drafts)) {
      if (v === null ? k in values : values[k] !== v) out[k] = v;
    }
    return out;
  }, [drafts, values]);
  const changeCount = Object.keys(changes).length;
  const errors = useMemo(() => {
    const out: Record<string, string> = {};
    for (const s of data?.schema ?? []) {
      const v = changes[s.key];
      if (typeof v === "string") {
        const e = validateValue(s, v);
        if (e) out[s.key] = e;
      }
    }
    return out;
  }, [changes, data]);
  const rawDirty = !!rawDraft && !!data && rawDraft.text !== data.raw;
  const rawStale = !!rawDraft && !!data && rawDraft.base !== data.raw;
  useReportDirty(changeCount > 0 || rawDirty, onDirtyChange);

  const onSaved = (res: PatchResult, what: string) => {
    qc.setQueryData<PropertiesResponse>(key, (old) =>
      old
        ? { ...old, exists: true, values: res.values, raw: res.raw, redacted_keys: res.redacted_keys ?? old.redacted_keys }
        : old,
    );
    qc.invalidateQueries({ queryKey: key });
    // server.properties is also shown in the file manager
    qc.invalidateQueries({ queryKey: [...qk.files(instance.id, "server.properties")] });
    if (res.changed.length === 0) toast.success("No changes to save");
    else toast.success(`${what}: ${res.changed.length} propert${res.changed.length === 1 ? "y" : "ies"} updated`);
    setRestartKeys(res.restart_required && res.changed.length ? res.changed : null);
  };

  const saveValues = useMutation({
    mutationFn: (vals: Record<string, string | null>) =>
      api.patch<PatchResult>(`/instances/${instance.id}/properties`, { values: vals }),
    onSuccess: (res) => {
      setDrafts({});
      onSaved(res, "Saved");
    },
    onError: (err) => toast.error(errorMessage(err)),
  });
  const saveRaw = useMutation({
    mutationFn: (raw: string) => api.patch<PatchResult>(`/instances/${instance.id}/properties`, { raw }),
    onSuccess: (res) => {
      setRawDraft(null);
      onSaved(res, "Saved raw file");
    },
  });

  const groups = useMemo(() => {
    const f = filter.trim().toLowerCase();
    const map = new Map<string, PropertySchema[]>();
    for (const s of data?.schema ?? []) {
      if (f && !s.key.toLowerCase().includes(f) && !s.label.toLowerCase().includes(f)) continue;
      const list = map.get(s.group) ?? [];
      list.push(s);
      map.set(s.group, list);
    }
    return [...map.entries()];
  }, [data, filter]);

  const otherKeys = useMemo(() => {
    const f = filter.trim().toLowerCase();
    const keys = new Set([...Object.keys(values), ...Object.keys(drafts)]);
    return [...keys]
      .filter((k) => !schemaKeys.has(k) && !managed.has(k))
      .filter((k) => !f || k.toLowerCase().includes(f))
      .sort((a, b) => a.localeCompare(b));
  }, [values, drafts, schemaKeys, managed, filter]);

  if (q.isLoading) return <LoadingState label="Reading server.properties…" />;
  if (q.error || !data) return <ErrorState error={q.error} title="Could not read server.properties" onRetry={() => q.refetch()} />;

  const setDraft = (k: string, v: string | null) => setDrafts((d) => ({ ...d, [k]: v }));
  const valueOf = (k: string): string | undefined => {
    if (k in drafts) return drafts[k] ?? undefined;
    return values[k];
  };
  const newKeyError = !newKey
    ? null
    : INVALID_KEY.test(newKey)
      ? "Keys cannot contain spaces, =, :, # or !"
      : managed.has(newKey)
        ? "This key is managed by MCPanel"
        : schemaKeys.has(newKey)
          ? "This key has its own field in the form above"
          : newKey in values || newKey in drafts
            ? "This key already exists"
            : newKey.length > 100
              ? "Key is too long"
              : null;
  const live = LIVE.includes(instance.status);
  const rawError = saveRaw.error instanceof ApiError ? (saveRaw.error.fieldErrors.raw ?? saveRaw.error.display) : saveRaw.error ? errorMessage(saveRaw.error) : null;

  return (
    <div className="grid grid-cols-1 gap-4">
      {!canEdit && <ReadOnlyNotice what="edit server.properties" />}
      {!data.exists && (
        <Notice title="server.properties has not been created yet">
          The server writes it with defaults on its first start. Values you save now are written to a new file and the server
          fills in the rest.
        </Notice>
      )}
      {restartKeys && (
        <RestartBanner
          instanceId={instance.id}
          keys={restartKeys}
          canControl={can("instance.control")}
          running={live}
          onDismiss={() => setRestartKeys(null)}
        />
      )}

      <div className="flex flex-wrap items-center gap-2">
        <Tabs value={mode} onValueChange={(v) => setMode(v as "form" | "raw")}>
          <TabsList aria-label="Editor mode">
            <TabsTrigger value="form">
              Form{changeCount > 0 && <span className="size-1.5 rounded-full bg-primary" aria-label="unsaved" />}
            </TabsTrigger>
            <TabsTrigger value="raw">
              Raw file{rawDirty && <span className="size-1.5 rounded-full bg-primary" aria-label="unsaved" />}
            </TabsTrigger>
          </TabsList>
        </Tabs>
        {mode === "form" && (
          <InputGroup className="w-full sm:ml-auto sm:w-64">
            <InputGroupAddon>
              <Search aria-hidden />
            </InputGroupAddon>
            <InputGroupInput
              aria-label="Find a property"
              placeholder="Find a property"
              value={filter}
              onChange={(e) => setFilter(e.target.value)}
            />
          </InputGroup>
        )}
      </div>

      {mode === "form" ? (
        <>
          {rawDirty && (
            <Notice tone="warning">You also have unsaved edits in the Raw file tab. Save or discard them separately.</Notice>
          )}
          {groups.length === 0 && otherKeys.length === 0 && (
            <EmptyState icon={<Search className="size-5" />} title="No properties match" description={`Nothing matches “${filter}”.`} />
          )}
          <div className="grid grid-cols-1 items-start gap-4 xl:grid-cols-2">
            {groups.map(([group, items]) => (
              <Section key={group} title={group}>
                <div className="grid gap-x-6 gap-y-5 sm:grid-cols-2">
                  {items.map((s) =>
                    redacted.has(s.key) && !(s.key in drafts) ? (
                      <div key={s.key} className="grid grid-cols-1 gap-0.5">
                        <span className="text-sm font-medium">{s.label}</span>
                        <span className="font-mono text-[10px] text-muted-foreground">{s.key}</span>
                        <HiddenValue />
                      </div>
                    ) : (
                      <PropertyControl
                        key={s.key}
                        schema={s}
                        value={valueOf(s.key)}
                        set={(v) => setDraft(s.key, v)}
                        disabled={!canEdit || saveValues.isPending}
                        error={errors[s.key] ?? null}
                      />
                    ),
                  )}
                </div>
              </Section>
            ))}
          </div>

          <Section
            title="Other properties"
            description="Keys in the file without a dedicated field (other mods or newer Minecraft versions may add their own)."
          >
            {otherKeys.length === 0 && !canEdit ? (
              <p className="text-sm text-muted-foreground">No other properties.</p>
            ) : (
              <div className="-mx-4 -my-4 overflow-x-auto">
                <table className="w-full text-sm">
                  <thead className="border-b bg-muted/30 text-xs text-muted-foreground">
                    <tr>
                      <th scope="col" className="h-8 px-3 text-left font-medium sm:px-4">
                        Key
                      </th>
                      <th scope="col" className="h-8 px-2 text-left font-medium">
                        Value
                      </th>
                      {canEdit && (
                        <th scope="col" className="h-8 w-12 px-2">
                          <span className="sr-only">Actions</span>
                        </th>
                      )}
                    </tr>
                  </thead>
                  <tbody>
                    {otherKeys.map((k) => {
                      const removed = drafts[k] === null;
                      const added = !(k in values);
                      const hidden = redacted.has(k) && !added;
                      return (
                        <tr key={k} className="border-b last:border-b-0">
                          <td className="px-3 py-1.5 align-middle sm:px-4">
                            <label
                              htmlFor={`other-${k}`}
                              className={cn("font-mono text-xs break-all", removed && "text-muted-foreground line-through")}
                            >
                              {k}
                            </label>
                            {added && <span className="ml-2 rounded bg-primary/10 px-1 text-[10px] text-primary">new</span>}
                          </td>
                          <td className="px-2 py-1.5 align-middle">
                            {hidden ? (
                              <HiddenValue id={`other-${k}`} />
                            ) : (
                              <Input
                                id={`other-${k}`}
                                value={removed ? (values[k] ?? "") : (valueOf(k) ?? "")}
                                onChange={(e) => setDraft(k, e.target.value)}
                                disabled={!canEdit || removed}
                                className="h-7 min-w-28 font-mono text-xs sm:min-w-40"
                                spellCheck={false}
                              />
                            )}
                          </td>
                          {canEdit && (
                            <td className="px-2 py-1.5 text-right align-middle">
                              {removed || added ? (
                                <Button
                                  variant="ghost"
                                  size="icon-sm"
                                  aria-label={added ? `Remove new key ${k}` : `Undo removal of ${k}`}
                                  onClick={() =>
                                    setDrafts((d) => {
                                      const next = { ...d };
                                      delete next[k];
                                      return next;
                                    })
                                  }
                                >
                                  {added ? <X /> : <Undo2 />}
                                </Button>
                              ) : (
                                <Button variant="ghost" size="icon-sm" aria-label={`Remove ${k} from the file`} onClick={() => setDraft(k, null)}>
                                  <Trash2 />
                                </Button>
                              )}
                            </td>
                          )}
                        </tr>
                      );
                    })}
                    {canEdit && (
                      <tr>
                        <td className="px-3 py-2 align-top sm:px-4">
                          <Label htmlFor="new-prop-key" className="sr-only">
                            New property key
                          </Label>
                          <Input
                            id="new-prop-key"
                            value={newKey}
                            onChange={(e) => setNewKey(e.target.value.trim())}
                            placeholder="new-key"
                            className="h-7 min-w-24 font-mono text-xs sm:min-w-32"
                            aria-invalid={!!newKeyError || undefined}
                            spellCheck={false}
                          />
                          <FieldError message={newKeyError} />
                        </td>
                        <td className="px-2 py-2 align-top">
                          <Label htmlFor="new-prop-value" className="sr-only">
                            New property value
                          </Label>
                          <Input
                            id="new-prop-value"
                            value={newValue}
                            onChange={(e) => setNewValue(e.target.value)}
                            placeholder="value"
                            className="h-7 min-w-28 font-mono text-xs sm:min-w-40"
                            spellCheck={false}
                          />
                        </td>
                        <td className="px-2 py-2 text-right align-top">
                          <Button
                            variant="outline"
                            size="icon-sm"
                            aria-label="Add property"
                            disabled={!newKey || !!newKeyError}
                            onClick={() => {
                              setDraft(newKey, newValue);
                              setNewKey("");
                              setNewValue("");
                            }}
                          >
                            <Plus />
                          </Button>
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            )}
          </Section>

          <Section
            title="Managed by MCPanel"
            description="Set through the container runtime on every start; edits to these keys are rejected or reverted."
          >
            <dl className="grid gap-3 sm:grid-cols-2">
              {data.managed_keys.map((k) => (
                <div key={k} className="grid grid-cols-1 gap-0.5">
                  <dt className="font-mono text-xs">{k}</dt>
                  <dd className="font-mono text-xs text-muted-foreground">
                    {values[k] === undefined ? "(not in file)" : redacted.has(k) ? <HiddenValue /> : values[k] || "(empty)"}
                  </dd>
                  {MANAGED_HELP[k] && <dd className="text-[11px] text-muted-foreground">{MANAGED_HELP[k]}</dd>}
                </div>
              ))}
            </dl>
          </Section>

          {canEdit && (
            <SaveBar
              count={changeCount}
              saving={saveValues.isPending}
              disabled={Object.keys(errors).length > 0}
              note={Object.keys(errors).length > 0 ? "Fix the highlighted values first" : live ? "Applied on the next restart" : undefined}
              onDiscard={() => setDrafts({})}
              onSave={() => saveValues.mutate(changes)}
            />
          )}
        </>
      ) : (
        <Section
          title="server.properties"
          description="Edit the file directly. Comments and ordering are kept. Managed keys cannot be changed here."
          actions={
            canEdit ? (
              <>
                <Button variant="outline" size="sm" onClick={() => setRawDraft(null)} disabled={!rawDraft || saveRaw.isPending}>
                  <Undo2 /> Discard
                </Button>
                <Button size="sm" onClick={() => rawDraft && saveRaw.mutate(rawDraft.text)} disabled={!rawDirty || saveRaw.isPending}>
                  {saveRaw.isPending ? <Loader2 className="animate-spin" /> : <Save />} Save file
                </Button>
              </>
            ) : undefined
          }
        >
          <div className="grid grid-cols-1 gap-3">
            {changeCount > 0 && (
              <Notice tone="warning">
                You have {changeCount} unsaved change{changeCount === 1 ? "" : "s"} in the form. Saving the raw file does not
                include them.
              </Notice>
            )}
            {rawStale && (
              <Notice
                tone="warning"
                title="The file changed since you started editing"
                action={
                  <Button size="sm" variant="outline" onClick={() => setRawDraft(null)}>
                    Load latest
                  </Button>
                }
              >
                Saving now overwrites those newer changes with your version.
              </Notice>
            )}
            <CodeEditor
              className="h-[60svh] min-h-64"
              ariaLabel="server.properties contents"
              value={rawDraft?.text ?? data.raw}
              readOnly={!canEdit}
              invalid={!!rawError}
              onChange={(text) => {
                setRawDraft((d) => ({ base: d?.base ?? data.raw, text }));
                if (saveRaw.error) saveRaw.reset();
              }}
              onKeyDown={(e) => {
                if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === "s") {
                  e.preventDefault();
                  if (rawDraft && rawDirty && !saveRaw.isPending) saveRaw.mutate(rawDraft.text);
                }
              }}
            />
            <FieldError message={rawError} />
            {canEdit && <p className="text-xs text-muted-foreground">Ctrl/⌘+S saves.</p>}
          </div>
        </Section>
      )}
    </div>
  );
}
