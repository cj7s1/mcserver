#!/bin/bash
# Build mcpanel.plg, the one file Unraid's plugin manager installs, from the readable sources in src/.
#
#   bash deploy/unraid/plugin/build.sh           write deploy/unraid/plugin/mcpanel.plg
#   bash deploy/unraid/plugin/build.sh --check   exit 1 when mcpanel.plg is not what a build gives now
#   bash deploy/unraid/plugin/build.sh --stdout  print it
#
# The build is reproducible: the same sources give the same file, byte for byte (no time stamps; the
# version is the first heading of CHANGES.md). Every file is inline (CDATA), so the plugin downloads
# nothing when it is installed. After a change of src/: a new entry in CHANGES.md, then build and commit
# both (backend/tests/test_deploy_unraid_plugin.py compares the committed file with a fresh build).
set -euo pipefail
export LC_ALL=C

# The repository the plugin manager downloads mcpanel.plg from when it checks for an update (pluginURL).
# A fork changes this one line.
BASE_URL="https://raw.githubusercontent.com/cj7s1/mcserver/main"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="${HERE}/src"
OUT="${HERE}/mcpanel.plg"
NAME=mcpanel
DEST="/usr/local/emhttp/plugins/${NAME}"
MIN_UNRAID=7.0.0
# the files the plugin installs: source (in src/), mode
FILES=(
    "MCPanel.page 0644"
    "mcpanel.css 0644"
    "mcpanel.js 0644"
    "include/common.php 0644"
    "include/action.php 0644"
    "bin/mcpanel 0755"
    "event/docker_started 0755"
)
# the scripts the plugin manager runs (not installed as files)
SCRIPTS=(install/pre-install.sh install/post-install.sh install/remove.sh)

die() {
    printf 'build.sh: %s\n' "$*" >&2
    exit 1
}

check_source() { # what the plugin manager does to an INLINE file (trim, then one newline) must not change it
    local f="$1" text
    [ -f "${SRC}/${f}" ] || die "missing: src/${f}"
    text="$(cat "${SRC}/${f}"; printf x)"
    text="${text%x}"
    case "${text}" in *']]>'*) die "src/${f} contains ']]>' (it ends the CDATA section)" ;; esac
    case "${text}" in *$'\r'*) die "src/${f} has CR line ends" ;; esac
    case "${text}" in [[:space:]]*) die "src/${f} begins with white space (the plugin manager trims it)" ;; esac
    case "${text}" in *[[:space:]]$'\n' | *[!$'\n']) die "src/${f} must end with exactly one newline" ;; esac
    return 0
}

version() {
    sed -n 's/^## \([0-9]\{4\}\.[0-9][0-9]\.[0-9][0-9][a-z]\{0,1\}\)$/\1/p' "${HERE}/CHANGES.md" | head -n 1
}

cdata() { # cdata FILE: its text inside a CDATA section
    printf '<![CDATA[\n'
    cat "$1"
    printf ']]>\n'
}

build() {
    local v entry src mode listed
    v="$(version)"
    [ -n "${v}" ] || die "CHANGES.md has no version heading (## YYYY.MM.DD)"
    for entry in "${FILES[@]}"; do check_source "${entry% *}"; done
    for src in "${SCRIPTS[@]}"; do check_source "${src}"; done
    # every source is built in: nothing in src/ is forgotten
    listed="$(printf '%s\n' "${FILES[@]% *}" "${SCRIPTS[@]}" | sort)"
    [ "$(cd "${SRC}" && find . -type f | sed 's|^\./||' | sort)" = "${listed}" ] ||
        die "src/ has files that FILES/SCRIPTS of build.sh do not name (or the other way round)"
    check_source ../CHANGES.md

    printf "<?xml version='1.0' standalone='yes'?>\n"
    printf '<!DOCTYPE PLUGIN>\n'
    printf '<!--\n'
    printf '  MCPanel plugin for Unraid 7. Built by deploy/unraid/plugin/build.sh from deploy/unraid/plugin/src/:\n'
    printf '  do not edit this file; edit the sources, add an entry to CHANGES.md and build again.\n'
    printf '  Install: Plugins > Install Plugin, with the pluginURL below. See docs/UNRAID.md, "The Unraid plugin".\n'
    printf '  Ran on one Unraid 7.3.4 server on 2026-11-12 (install, boot tasks, firewall); not everything yet.\n'
    printf -- '-->\n'
    printf '<PLUGIN name="%s" author="MCPanel" version="%s" pluginURL="%s/deploy/unraid/plugin/%s.plg" min="%s" launch="Settings/MCPanel" icon="gamepad">\n' \
        "${NAME}" "${v}" "${BASE_URL}" "${NAME}" "${MIN_UNRAID}"
    printf '\n<CHANGES>\n'
    cdata "${HERE}/CHANGES.md"
    printf '</CHANGES>\n'
    printf '\n<!-- 1. the files of the version before go (the plugin manager never overwrites a file); the shutdown hook stays -->\n'
    printf '<FILE Run="/bin/bash">\n<INLINE>\n'
    cdata "${SRC}/install/pre-install.sh"
    printf '</INLINE>\n</FILE>\n'
    printf '\n<!-- 2. the files (in RAM: rebuilt at every boot) -->\n'
    for entry in "${FILES[@]}"; do
        src="${entry% *}"
        mode="${entry#* }"
        printf '<FILE Name="%s/%s" Mode="%s">\n<INLINE>\n' "${DEST}" "${src}" "${mode}"
        cdata "${SRC}/${src}"
        printf '</INLINE>\n</FILE>\n\n'
    done
    printf '<!-- 3. modes, the settings folder; nothing is started (at boot Docker is not up yet) -->\n'
    printf '<FILE Run="/bin/bash">\n<INLINE>\n'
    cdata "${SRC}/install/post-install.sh"
    printf '</INLINE>\n</FILE>\n'
    printf '\n<!-- removal: the page, the programs, the event scripts and the shutdown hook in the event folder -->\n'
    printf '<FILE Run="/bin/bash" Method="remove">\n<INLINE>\n'
    cdata "${SRC}/install/remove.sh"
    printf '</INLINE>\n</FILE>\n'
    printf '</PLUGIN>\n'
}

case "${1:-}" in
    "")
        build >"${OUT}.new"
        mv -f "${OUT}.new" "${OUT}"
        printf 'built %s (version %s)\n' "${OUT}" "$(version)"
        ;;
    --stdout) build ;;
    --check)
        if ! cmp -s <(build) "${OUT}"; then
            die "mcpanel.plg is not what the sources give: run 'bash deploy/unraid/plugin/build.sh' and commit it"
        fi
        printf 'mcpanel.plg is up to date (version %s)\n' "$(version)"
        ;;
    *)
        printf 'usage: bash build.sh [--check|--stdout]\n' >&2
        exit 64
        ;;
esac
